import hashlib
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from lanes import node_modules as nm


class NodeCacheTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.ws = self.root / 'workspace'
        self.ws.mkdir()
        (self.ws / 'package.json').write_text('{"private":true}')
        (self.ws / 'package-lock.json').write_text('{"lockfileVersion":3}')
        self.entry = self.root / 'entry'
        (self.entry / 'node_modules' / '.bin').mkdir(parents=True)
        (self.entry / 'node_modules' / 'package.js').write_text('cached bytes')
        (self.entry / 'node_modules' / '.bin' / 'tool').symlink_to('../package.js')
        (self.entry / 'manifest.json').write_text(json.dumps({'inputs': nm.inputs(self.ws)}))

    def test_restore_is_private_and_replaces_stale_files(self):
        nm.restore(self.entry, self.ws)
        target = self.ws / 'node_modules' / 'package.js'
        self.assertEqual(target.read_text(), 'cached bytes')
        self.assertNotEqual(target.stat().st_ino, (self.entry / 'node_modules' / 'package.js').stat().st_ino)
        target.write_text('cell mutation')
        (self.ws / 'node_modules' / 'stale').write_text('stale')
        nm.restore(self.entry, self.ws)
        self.assertEqual(target.read_text(), 'cached bytes')
        self.assertFalse((self.ws / 'node_modules' / 'stale').exists())
        self.assertEqual((self.ws / 'node_modules' / '.bin' / 'tool').readlink(), Path('../package.js'))

    def test_changed_install_inputs_refuse(self):
        for name in ('package.json', 'package-lock.json', '.npmrc'):
            with self.subTest(name=name):
                p=self.ws/name
                before=p.read_bytes() if p.exists() else None
                p.write_text('changed')
                with self.assertRaisesRegex(ValueError, 'install inputs changed'):
                    nm.restore(self.entry, self.ws)
                p.unlink() if before is None else p.write_bytes(before)

    def test_missing_cache_refuses_without_running_npm(self):
        with patch.dict(os.environ, {'LANES_NPM_CACHE':str(self.root/'missing')}), patch('subprocess.run') as run:
            with self.assertRaisesRegex(ValueError, 'not staged'):
                nm.entry_for(self.ws)
            run.assert_not_called()

    def test_recipe_scope(self):
        self.assertEqual(nm.recipe(nm.COMMAND), '.')
        self.assertEqual(nm.recipe('(cd packaging/cucumber && '+nm.COMMAND+')'), 'packaging/cucumber')
        for command in ('npm install', 'npm ci', '(cd ../other && '+nm.COMMAND+')', nm.COMMAND+' && other'):
            self.assertIsNone(nm.recipe(command))
