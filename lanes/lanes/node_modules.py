"""Install locked npm dependencies at staging; restore private copies without npm."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import tomllib

COMMAND = 'npm ci --ignore-scripts --no-audit --no-fund'
FLAGS = ['ci', '--ignore-scripts', '--no-audit', '--no-fund']
DEFAULT_CACHE = Path(__file__).resolve().parents[2] / 'node-cache'


def inputs(start):
    h = hashlib.sha256(COMMAND.encode())
    for name in ('package.json', 'package-lock.json', '.npmrc'):
        p = Path(start) / name
        if not p.is_file() and name != '.npmrc':
            raise ValueError(f'{p}: locked npm setup requires this file')
        h.update(name.encode() + b'\0' + (p.read_bytes() if p.is_file() else b'<absent>') + b'\0')
    return h.hexdigest()


def recipe(command):
    if command == COMMAND:
        return '.'
    match = re.fullmatch(r'\(cd ([a-zA-Z0-9_./-]+) && ' + re.escape(COMMAND) + r'\)', command)
    if match and '..' not in Path(match[1]).parts and not Path(match[1]).is_absolute():
        return match[1]
    return None


def recipes(task):
    with open(Path(task) / 'task.toml', 'rb') as f:
        return [rel for cmd in tomllib.load(f).get('setup', []) if (rel := recipe(cmd)) is not None]


def cache_root():
    return Path(os.environ.get('LANES_NPM_CACHE', DEFAULT_CACHE)).resolve()


def entry_for(start):
    root = cache_root()
    digest = inputs(start)
    index = root / 'inputs' / (digest + '.json')
    if not index.is_file():
        raise ValueError(f'npm dependencies not staged for {start}; run lanes-stage --tasks KIT')
    record = json.loads(index.read_text())
    entry = root / record['key']
    if json.loads((entry / 'manifest.json').read_text())['inputs'] != digest:
        raise ValueError(f'npm cache manifest mismatch: {entry}')
    if not (entry / 'node_modules').is_dir():
        raise ValueError(f'npm cache missing node_modules: {entry}')
    return entry


def setup(task, commands):
    result = []
    for command in commands:
        rel = recipe(command)
        if rel is not None:
            entry = entry_for(Path(task) / 'start' / rel)
            command = shlex.join([sys.executable, str(Path(__file__).resolve()), 'restore', '--entry', str(entry)])
            if rel != '.':
                command = '(cd ' + shlex.quote(rel) + ' && ' + command + ')'
        result.append(command)
    return result


def copy_modules(source, dest):
    # APFS clones share disk blocks, never mutable inodes. No hardlinks or symlinked cache trees.
    if sys.platform == 'darwin':
        p = subprocess.run(['/bin/cp', '-cR', str(source), str(dest)], capture_output=True)
        if p.returncode == 0:
            return
        if Path(dest).exists():
            shutil.rmtree(dest)
    shutil.copytree(source, dest, symlinks=True)


def restore(entry, workspace):
    entry, workspace = Path(entry), Path(workspace)
    manifest = json.loads((entry / 'manifest.json').read_text())
    if inputs(workspace) != manifest['inputs']:
        raise ValueError('npm install inputs changed; stage the new lockfile before running')
    temporary = Path(tempfile.mkdtemp(prefix='.lanes-npm-', dir=workspace))
    try:
        copy_modules(entry / 'node_modules', temporary / 'node_modules')
        dest = workspace / 'node_modules'
        if dest.is_symlink():
            dest.unlink()
        elif dest.exists():
            shutil.rmtree(dest)
        os.replace(temporary / 'node_modules', dest)
    finally:
        shutil.rmtree(temporary)


def prepare_workspace(start, ws):
    task = Path(start).parent
    if (task / 'task.toml').is_file():
        for rel in recipes(task):
            restore(entry_for(Path(start) / rel), Path(ws) / rel)


def stage(task, rel):
    start = Path(task) / 'start' / rel
    digest, root = inputs(start), cache_root()
    root.mkdir(parents=True, exist_ok=True)
    (root / 'inputs').mkdir(exist_ok=True)
    with open(root / (digest + '.lock'), 'a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if (root / 'inputs' / (digest + '.json')).is_file():
            print(f'{Path(task).name}: reuse {entry_for(start).name}', flush=True)
            return
        npm, node = shutil.which('npm'), shutil.which('node')
        if not npm or not node:
            raise ValueError('npm and node must be available at staging')
        toolchain = {name: subprocess.check_output([path, '--version'], text=True).strip()
                     for name, path in [('npm', npm), ('node', node)]}
        toolchain.update(platform=platform.system(), arch=platform.machine())
        # Workspace/file dependencies need more inputs than these task kits declare.
        package = json.loads((start / 'package.json').read_text())
        locked = json.loads((start / 'package-lock.json').read_text())
        if package.get('workspaces') or any(p.get('link') or str(p.get('resolved', '')).startswith('file:')
                                            for p in locked.get('packages', {}).values()):
            raise ValueError('local/workspace npm dependencies require an expanded staging key')
        key = hashlib.sha256((digest + json.dumps(toolchain, sort_keys=True)).encode()).hexdigest()
        entry = root / key
        if not entry.exists():
            temporary = Path(tempfile.mkdtemp(prefix='staging-', dir=root))
            try:
                # The same project files and npm flags as the original setup.
                shutil.copytree(start, temporary / 'ws', symlinks=True,
                                ignore=shutil.ignore_patterns('node_modules', '.git'))
                subprocess.run([npm, *FLAGS], cwd=temporary / 'ws', check=True)
                if inputs(temporary / 'ws') != digest:
                    raise ValueError('npm ci changed its install inputs')
                os.rename(temporary / 'ws' / 'node_modules', temporary / 'node_modules')
                shutil.rmtree(temporary / 'ws')
                (temporary / 'manifest.json').write_text(json.dumps({'inputs': digest, 'key': key,
                    'toolchain': toolchain, 'command': COMMAND}, indent=2) + '\n')
                os.rename(temporary, entry)
            finally:
                if temporary.exists():
                    shutil.rmtree(temporary)
        index = root / 'inputs' / (digest + '.json')
        tmp_index = index.with_suffix('.tmp')
        tmp_index.write_text(json.dumps({'key': key}) + '\n')
        os.replace(tmp_index, index)
        print(f'{Path(task).name}: staged {key}', flush=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='action', required=True)
    s = sub.add_parser('stage')
    s.add_argument('--tasks', required=True)
    s.add_argument('--run-dir')
    s.add_argument('task_ids', nargs='*')
    r = sub.add_parser('restore')
    r.add_argument('--entry', required=True)
    a = p.parse_args()
    try:
        if a.action == 'restore':
            restore(a.entry, Path.cwd())
        else:
            tasks = a.task_ids
            if a.run_dir:
                experiment = json.loads((Path(a.run_dir) / 'experiment.json').read_text())
                if experiment.get('phase') == 'probe':
                    return
                tasks = experiment['tasks']
            for task in tasks or sorted(p.name for p in Path(a.tasks).iterdir() if (p / 'task.toml').is_file()):
                for rel in recipes(Path(a.tasks) / task):
                    stage(Path(a.tasks) / task, rel)
    except (OSError, ValueError, subprocess.CalledProcessError) as e:
        p.exit(1, f'lanes-stage: {e}\n')


if __name__ == '__main__':
    main()
