#!/usr/bin/env python3
"""Report identical replay step lists; never modify or delete case files."""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import sys

# Reuse the runner's ITF decoding and structural equality without source-digest
# validation: other patch jobs may change the models before this is rerun.
sys.dont_write_bytecode = True
SUITE_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SUITE_ROOT))
from kogen_conformance.quint_runner import decode_itf, _freeze


def id_key(case_id):
    """Order numeric ID components numerically (including Quint seeds)."""
    return tuple((1, int(part)) if part.isdigit() else (0, part)
                 for part in re.split(r"(\d+)", case_id))


def duplicate_groups(cases_dir):
    buckets = defaultdict(list)
    seen = set()
    for path in sorted(cases_dir.rglob("*.json")):
        if path.name.endswith(".manifest.json"):
            continue
        case = json.loads(path.read_text(encoding="utf-8"))
        if path.name.endswith(".itf.json"):
            manifest_path = path.with_name(
                path.name[:-len(".itf.json")] + ".manifest.json")
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            case_id = f"quint.{manifest['module']}.seed-{manifest['seed']}"
            # The runner replays every lastStep entry, in state order. Empty
            # states and state boundaries have no step-list significance.
            steps = [step for state in decode_itf(case)["states"]
                     for step in state[manifest["last_step_var"]]]
        else:
            case_id = case["id"]
            steps = case["steps"]
        if not isinstance(steps, list) or not steps:
            raise ValueError(f"{path}: expected a non-empty step list")
        if case_id in seen:
            raise ValueError(f"{path}: duplicate case ID {case_id}")
        seen.add(case_id)
        # Record/map/set order is irrelevant; list order, strings, values and
        # ITF variant tags remain exact. Case metadata is outside the key.
        buckets[_freeze(steps)].append(case_id)
    groups = [sorted(ids, key=id_key) for ids in buckets.values() if len(ids) > 1]
    groups.sort(key=lambda ids: id_key(ids[0]))
    return len(seen), groups


def render_report(total, groups):
    dropped = sorted((case_id for group in groups for case_id in group[1:]),
                     key=id_key)
    lines = [
        "# T2: identical trace deduplication",
        "",
        "Generated by `python3 conformance/bin/t2_dedupe.py`. No case files are deleted.",
        "",
        "Scope: all JSON cases under `conformance/cases/`, including Quint traces;",
        "companion manifests are metadata, not separate cases. No scoring exclusions",
        "are applied, and Gherkin scenarios outside this directory are not counted.",
        "",
        "Equality compares only normalized step lists, ignoring case ID, seed, name",
        "and other case metadata. Quint ITF steps are decoded and flattened in replay",
        "order. Record, map and set ordering is ignored; list order and all step",
        "values are preserved. The lowest ID (numeric seed order) is retained.",
        "",
        f"N_total before: **{total}**",
        f"N_total after applying the dropped-ID list: **{total - len(dropped)}**",
        f"Duplicate groups: **{len(groups)}**; dropped IDs: **{len(dropped)}**.",
        "",
        "## Groups (kept ID ← dropped IDs)",
        "",
    ]
    lines.extend(f"- `{group[0]}` ← " + ", ".join(f"`{item}`" for item in group[1:])
                 for group in groups)
    lines += ["", "## Dropped IDs", "", "```text", *dropped, "```", "",
              "Assembler: apply the list by case ID. For Quint cases, remove or exclude",
              "the matching ITF trace and its companion manifest together. Rerun this",
              "report if assembled patches change case steps, then run",
              "`python3 conformance/bin/suite_sha.py` after all changes and removals.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cases", type=Path, default=SUITE_ROOT / "cases")
    parser.add_argument("--output", type=Path, help="write Markdown here instead of stdout")
    args = parser.parse_args()
    if not args.cases.is_dir():
        parser.error(f"case directory does not exist: {args.cases}")
    report = render_report(*duplicate_groups(args.cases))
    if args.output:
        args.output.write_text(report, encoding="utf-8")
    else:
        sys.stdout.write(report)


if __name__ == "__main__":
    main()
